# -*- coding: utf-8 -*-
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from evaluate import is_correct

cases = [
    # ---- 单选题 ----
    ("A", "A", "单选题", True),
    ("答案：B", "B", "单选题", True),
    ("我认为应该选 C。", "C", "单选题", True),
    ("D", "A", "单选题", False),

    # ---- 基础归一化 ----
    ("18", "18", "填空题", True),
    (" 18 ", "18", "填空题", True),
    ("x=3", "x=3", "填空题", True),
    ("X＝3", "x=3", "填空题", True),

    # ---- 数值等价 ----
    ("0.5", "1/2", "填空题", True),
    ("(2)/(5)", "2/5", "填空题", True),
    ("-1+√2-1-1", "√2-3", "解答题", True),

    # ---- LaTeX / 说明文字 ----
    (r"\(1.1\times 10^{12}\)", "1.1×10¹²", "填空题", True),
    (r"\(\frac{1}{6}\)", "1/6", "填空题", True),
    ("3（答案不唯一）", "3", "填空题", True),
    ("y = -x² + 1（答案不唯一）", "-x²+1（答案不唯一）", "填空题", True),

    # ---- 等式前缀 ----
    ("3", "x=3", "填空题", True),

    # ---- 不等式的两种写法 ----
    ("x>3；x<10/3", "3<x<10/3", "解答题", True),

    # ---- 多问答案 ----
    ("（1）60；（2）m=11，α=66°", "（1）60；（2）m=11，α=66°", "解答题", True),
    ("（1）60；（2）m=11，α=66°", "（1）60；（2）m=11，α=66°；（3）100；（4）1/6", "解答题", False),
    ("（1）k<3/4；（2）k=-2", "（1）k>3/4；（2）k=2", "解答题", False),

    # ---- 写了推导链，最后一段才是答案 ----
    ("x(x²-49) = x(x+7)(x-7)", "x(x+7)(x-7)", "填空题", True),
    ("n² - 100 = (n + 10)(n - 10)", "(n+10)(n-10)", "填空题", True),
    ("2(a² - 1) = 2(a + 1)(a - 1)", "2(a+1)(a-1)", "填空题", True),
    ("x(x+7)(x+8)", "x(x+7)(x-7)", "填空题", False),

    # ---- 末尾带单位/量词 ----
    ("1.1 × 10^12 元", "1.1×10¹²", "填空题", True),
    ("833棵", "833", "填空题", True),
    ("100名学生", "100", "解答题", True),
    ("1000名学生", "100", "解答题", False),

    # ---- LaTeX 关系符与作答前缀 ----
    (r"定义域为 \( x \neq 23 \)。", "x ≠ 23", "填空题", True),
    (r"$x \le 5$", "x ≤ 5", "填空题", True),

    # ---- 序号分隔符 ----
    ("①；②；③；④", "①，②，③，④", "解答题", True),
    ("②；③；④", "①，②，③，④", "解答题", False),

    # ---- 明确错误 ----
    ("-2", "-1", "解答题", False),
    ("45°", "90°", "填空题", False),
]

ok = 0
for pred, gold, qtype, expected in cases:
    got = is_correct(pred, gold, qtype)
    flag = "OK " if got == expected else "FAIL"
    if got == expected:
        ok += 1
    else:
        print(f"{flag} [{qtype}] pred={pred!r} gold={gold!r} -> {got} (expected {expected})")

print(f"{ok}/{len(cases)} passed")
